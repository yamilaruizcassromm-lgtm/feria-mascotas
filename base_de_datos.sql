-- 1. Crear la tabla con clave primaria y tipos de datos adecuados
CREATE TABLE animales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    especie TEXT NOT NULL,
    edad_meses INTEGER NOT NULL,
    fecha_ingreso DATE NOT NULL,
    estado TEXT NOT NULL CHECK (estado IN ('disponible', 'adoptado'))
);

-- 2. Habilitar acceso público (RLS) para que el sitio web pueda hacer CRUD sin errores de permisos
ALTER TABLE animales ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Permitir lectura publica" ON animales FOR SELECT USING (true);
CREATE POLICY "Permitir insercion publica" ON animales FOR INSERT WITH CHECK (true);
CREATE POLICY "Permitir actualizacion publica" ON animales FOR UPDATE USING (true);
CREATE POLICY "Permitir eliminacion publica" ON animales FOR DELETE USING (true);

